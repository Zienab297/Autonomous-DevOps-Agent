class Severity(str, Enum):
    LOW      = "low"
    MEDIUM   = "medium"
    HIGH     = "high"
    CRITICAL = "critical"


class IncidentStatus(str, Enum):
    OPEN          = "open"
    INVESTIGATING = "investigating"
    REMEDIATING   = "remediating"
    RESOLVED      = "resolved"
    FAILED        = "failed"


class AgentStatus(str, Enum):
    IDLE    = "idle"
    RUNNING = "running"
    STOPPED = "stopped"
    ERROR   = "error"


class DeploymentStatus(str, Enum):
    PENDING     = "pending"
    RUNNING     = "running"
    SUCCESS     = "success"
    FAILED      = "failed"
    ROLLED_BACK = "rolled_back"


class RemediationStatus(str, Enum):
    PENDING  = "pending"
    APPROVED = "approved"
    RUNNING  = "running"
    SUCCESS  = "success"
    FAILED   = "failed"
    REJECTED = "rejected"

class VerificationStatus(str, Enum):
    PASS    = "PASS"
    FAIL    = "FAIL"
    UNKNOWN = "UNKNOWN"     # LLM could not determine from outputs
