@dataclass
class Metric:
    """A single metric reading from the Monitoring Agent."""
    name: str
    value: float
    unit: str
    service: str
    timestamp: datetime = field(default_factory=datetime.utcnow)
    labels: Dict[str, str] = field(default_factory=dict)

    def __str__(self):
        return f"Metric({self.name}={self.value}{self.unit}, service={self.service})"


@dataclass
class Log:
    """A single log entry from the Monitoring Agent."""
    message: str
    level: str
    service: str
    timestamp: datetime = field(default_factory=datetime.utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def __str__(self):
        return f"Log({self.level}: {self.message[:60]}...)"


@dataclass
class Incident:
    """
    An Incident is created by the Monitoring Agent
    and passed to the Knowledge Agent for investigation.

    Example:
        Incident(
            service="auth-api",
            severity=Severity.HIGH,
            description="API error rate > 40%"
        )
    """
    service: str
    severity: Severity
    description: str
    incident_id: str = field(default_factory=lambda: f"INC-{str(uuid.uuid4())[:8].upper()}")
    status: IncidentStatus = IncidentStatus.OPEN
    metrics: List[Metric] = field(default_factory=list)
    logs: List[Log] = field(default_factory=list)
    created_at: datetime = field(default_factory=datetime.utcnow)
    updated_at: datetime = field(default_factory=datetime.utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def __str__(self):
        return (
            f"Incident(id={self.incident_id}, "
            f"service={self.service}, "
            f"severity={self.severity.value}, "
            f"status={self.status.value})"
        )


